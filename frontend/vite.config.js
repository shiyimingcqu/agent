// ============================================================
// vite.config.js —— Vite 的配置文件
// ============================================================
//
// Vite 是前端的“开发服务器 + 打包工具”：
//   - 执行 npm run dev  时，它启动 5173 端口的开发服务器，并支持热更新；
//   - 执行 npm run build 时，它把代码打包成可部署的静态文件。
// 这个文件在 Vite 启动时读一次，用来告诉它“该怎么工作”。

import { defineConfig } from "vite";
// 导入 Vue 插件：让 Vite 能识别并编译 .vue 单文件组件
import vue from "@vitejs/plugin-vue";

// defineConfig 只是包一层，好处是编辑器能给配置项自动补全和类型提示
export default defineConfig({
  // 注册插件。没有它，Vite 不知道该怎么处理 .vue 文件。
  plugins: [vue()],

  server: {
    // ---------- 代理（proxy）—— 本项目最关键的配置 ----------
    //
    // 问题：前端开发服务器在 5173 端口，FastAPI 在 8000 端口，
    //       两者“源”不同（端口不同就算不同源），浏览器会以跨域(CORS)为由拦截请求。
    //
    // 解决：让 Vite 当中间人。
    //       前端仍旧写 fetch("/chat")，看起来是发给 5173 自己；
    //       Vite 收到后，按下面这条规则，把请求转发到 8000 的 FastAPI。
    //       对浏览器而言全程同源，所以不存在跨域问题。
    //
    // 格式：冒号左边是“匹配的路径前缀”，右边是“要转发到的地址”。
    proxy: {
      // 凡是以 /chat 或 /history 开头的请求，都转发给本机的 FastAPI
      "/chat": "http://127.0.0.1:8000",
      "/history": "http://127.0.0.1:8000",
      "/documents": "http://127.0.0.1:8000",
      "/search": "http://127.0.0.1:8000",

    },
  },
});